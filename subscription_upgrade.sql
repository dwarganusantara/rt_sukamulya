CREATE TABLE IF NOT EXISTS platform_admins (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(100) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, is_active TINYINT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS platform_login_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ip_hash CHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY idx_attempt (ip_hash,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS subscription_catalog (
 feature_code VARCHAR(80) NOT NULL PRIMARY KEY,
 commercial_type ENUM('FREE','PREMIUM','DISABLED') NOT NULL DEFAULT 'FREE',
 description VARCHAR(500) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS subscription_plans (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 price DECIMAL(15,2) NOT NULL DEFAULT 0, duration_days INT UNSIGNED NOT NULL,
 is_active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS subscription_plan_features (
 plan_id INT UNSIGNED NOT NULL, feature_code VARCHAR(80) NOT NULL,
 PRIMARY KEY(plan_id,feature_code), FOREIGN KEY(plan_id) REFERENCES subscription_plans(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tenant_subscriptions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, tenant_id INT UNSIGNED NOT NULL,
 plan_id INT UNSIGNED NOT NULL, status ENUM('ACTIVE','TRIAL','EXPIRED','SUSPENDED') NOT NULL,
 starts_at DATETIME NOT NULL, ends_at DATETIME NOT NULL, reason VARCHAR(500) NOT NULL,
 created_by INT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_tenant (tenant_id,id), FOREIGN KEY(plan_id) REFERENCES subscription_plans(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS subscription_overrides (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, tenant_id INT UNSIGNED NOT NULL,
 feature_code VARCHAR(80) NOT NULL, access_mode ENUM('GRANT','DENY') NOT NULL,
 starts_at DATETIME NOT NULL, ends_at DATETIME NOT NULL, reason VARCHAR(500) NOT NULL,
 created_by INT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_override (tenant_id,feature_code,starts_at,ends_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS subscription_audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor_id INT UNSIGNED NOT NULL,
 tenant_id INT UNSIGNED NULL, action VARCHAR(60) NOT NULL, before_json MEDIUMTEXT,
 after_json MEDIUMTEXT, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_audit_tenant (tenant_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS subscription_plan_details (
 plan_id INT UNSIGNED NOT NULL PRIMARY KEY, description VARCHAR(300) NOT NULL DEFAULT '',
 benefits_json TEXT NOT NULL, theme VARCHAR(12) NOT NULL DEFAULT 'orange',
 sort_order INT NOT NULL DEFAULT 0, version INT UNSIGNED NOT NULL DEFAULT 1,
 FOREIGN KEY(plan_id) REFERENCES subscription_plans(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
